import * as React from 'react'
import { AnimatePresence, motion } from 'motion/react'
import { cn } from '@/shared/lib/utils'
import { useControllableOpen } from '@/shared/lib/use-controllable-open'
import { useOverlayMotion } from '@/shared/motion/use-motion-preset'
import { DropdownMenu as DropdownMenuPrimitive } from 'radix-ui'
import { CheckIcon, ChevronRightIcon } from 'lucide-react'

// nudo-tsl: menus animate their exit with motion/react, so their content needs the open state.
const DropdownMenuOpenContext = React.createContext(false)
const DropdownMenuSubOpenContext = React.createContext(false)

function DropdownMenu({
  open,
  defaultOpen,
  onOpenChange,
  ...props
}: React.ComponentProps<typeof DropdownMenuPrimitive.Root>) {
  const [isOpen, setOpen] = useControllableOpen({ open, defaultOpen, onOpenChange })
  return (
    <DropdownMenuOpenContext value={isOpen}>
      <DropdownMenuPrimitive.Root
        data-slot="dropdown-menu"
        open={isOpen}
        onOpenChange={setOpen}
        {...props}
      />
    </DropdownMenuOpenContext>
  )
}

function DropdownMenuPortal({
  ...props
}: React.ComponentProps<typeof DropdownMenuPrimitive.Portal>) {
  return <DropdownMenuPrimitive.Portal data-slot="dropdown-menu-portal" {...props} />
}

function DropdownMenuTrigger({
  ...props
}: React.ComponentProps<typeof DropdownMenuPrimitive.Trigger>) {
  return <DropdownMenuPrimitive.Trigger data-slot="dropdown-menu-trigger" {...props} />
}

// nudo-tsl: grows from its trigger (the menu preset); instant when opened from the keyboard.
function DropdownMenuContent({
  className,
  align = 'start',
  sideOffset = 4,
  children,
  ...props
}: React.ComponentProps<typeof DropdownMenuPrimitive.Content>) {
  const isOpen = React.useContext(DropdownMenuOpenContext)
  const { presence, element, presenceKey } = useOverlayMotion('menu', isOpen)
  return (
    <AnimatePresence key={presenceKey} {...presence}>
      {isOpen && (
        <DropdownMenuPrimitive.Portal forceMount key="dropdown-menu">
          <DropdownMenuPrimitive.Content
            data-slot="dropdown-menu-content"
            sideOffset={sideOffset}
            align={align}
            {...props}
            forceMount
            asChild
          >
            <motion.div
              {...element}
              className={cn(
                'z-50 max-h-(--radix-dropdown-menu-content-available-height) w-(--radix-dropdown-menu-trigger-width) min-w-32 origin-(--radix-dropdown-menu-content-transform-origin) overflow-x-hidden overflow-y-auto rounded-lg bg-popover p-1 text-popover-foreground shadow-md ring-1 ring-foreground/10 data-closed:pointer-events-none',
                className,
              )}
            >
              {children}
            </motion.div>
          </DropdownMenuPrimitive.Content>
        </DropdownMenuPrimitive.Portal>
      )}
    </AnimatePresence>
  )
}

