/** Invert the local UV-to-screen Jacobian to measure a fixed cell center in render pixels. */
function pixelMotes(layer: 'A' | 'B', scale: number) {
  return {
    nodes: [
      node(`dust${layer}`, 'effects/voronoi', {
        scale: float(scale),
        jitter: float(layer === 'A' ? 1 : 10.45793),
      }),
      node(`cellUv${layer}`, 'math/divide', { b: float(scale) }),
      node(`cellOffset${layer}`, 'math/subtract'),
      node(`pixelX${layer}`, 'vector/dot'),
      node(`pixelY${layer}`, 'vector/dot'),
      node(`pixelVector${layer}`, 'vector/combine'),
      node(`pixelLength${layer}`, 'vector/length'),
      node(`pixelDistance${layer}`, 'math/divide'),
      node(`dustRamp${layer}`, 'interpolation/smoothstep'),
      node(`motes${layer}`, 'math/one-minus'),
    ],
    wires: [
      ['uv.out', `dust${layer}.uv`],
      [`dust${layer}.cell`, `cellUv${layer}.a`],
      ['uv.out', `cellOffset${layer}.a`],
      [`cellUv${layer}.out`, `cellOffset${layer}.b`],
      [`cellOffset${layer}.out`, `pixelX${layer}.a`],
      [`cellOffset${layer}.out`, `pixelY${layer}.a`],
      ['pixelBasisY.out', `pixelX${layer}.b`],
      ['pixelBasisX.out', `pixelY${layer}.b`],
      [`pixelX${layer}.out`, `pixelVector${layer}.x`],
      [`pixelY${layer}.out`, `pixelVector${layer}.y`],
      [`pixelVector${layer}.vec2`, `pixelLength${layer}.in`],
      [`pixelLength${layer}.out`, `pixelDistance${layer}.a`],
      ['safePixelArea.out', `pixelDistance${layer}.b`],
      [`pixelDistance${layer}.out`, `dustRamp${layer}.in`],
      ['particleInner.out', `dustRamp${layer}.edge0`],
      ['particleOuter.out', `dustRamp${layer}.edge1`],
      [`dustRamp${layer}.out`, `motes${layer}.in`],
    ] satisfies readonly WireSpec[],
  }
}

